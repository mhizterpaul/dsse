from dataclasses import dataclass
import numpy as np
from pathlib import Path

@dataclass
class EMTWaveforms:
    time_s: np.ndarray
    voltages: dict  # dict of {transformer_id: (N, 3)}
    currents: dict  # dict of {transformer_id: (N, 3)}
    event_metadata: dict
    frequency_hz: float

    @property
    def feeder_voltage_abc(self):
        return self.voltages

    @property
    def feeder_current_abc(self):
        return self.currents

    @property
    def transformer_voltage_abc(self):
        return self.voltages

    @property
    def transformer_current_abc(self):
        return self.currents


def _parse_native_binary_pl4(filepath: Path) -> np.ndarray:
    """
    Parses native ATP binary PL4 file generated by tpbig/tpbigm executable.
    Dynamically finds the start of float32 waveform records and channel count,
    reshaping data into (N, num_channels).
    """
    with open(filepath, "rb") as f:
        raw_data = f.read()

    best_offset = -1
    best_ncols = -1

    for ncols in range(2, 30):
        for offset in range(32, min(2048, len(raw_data) - ncols * 5 * 4), 4):
            arr = np.frombuffer(raw_data[offset:], dtype=np.float32)
            if len(arr) >= ncols * 5:
                t0 = arr[0]
                t1 = arr[ncols]
                t2 = arr[ncols * 2]
                dt = t1 - t0
                if abs(t0) < 1e-4 and 1e-6 <= dt <= 1e-2 and abs((t2 - t1) - dt) < 1e-6:
                    best_offset = offset
                    best_ncols = ncols
                    break
        if best_offset >= 0:
            break

    if best_offset < 0 or best_ncols < 0:
        raise ValueError(f"Could not locate float32 waveform data in binary PL4 file '{filepath}'")

    data = np.frombuffer(raw_data[best_offset:], dtype=np.float32)
    n_rows = len(data) // best_ncols
    if n_rows == 0:
        raise ValueError(f"Binary PL4 file '{filepath}' contains zero complete rows")

    data_matrix = data[: n_rows * best_ncols].reshape(n_rows, best_ncols)
    return data_matrix


class ATPOutputReader:
    """
    Parses .pl4 output generated by ATPRunner into raw EMTWaveforms.
    Supports binary PL4 (via pyatp, atp_utils, or native float32 parser) and text PL4 formats.
    Raises ValueError with stack trace if any required file, event parameter, or waveform data is missing or invalid.
    """
    def __init__(self):
        pass

    def read(self, atp_result, event, transformer_id: str = "trans1") -> EMTWaveforms:
        if atp_result is None or not hasattr(atp_result, "case_path"):
            raise ValueError(f"Invalid atp_result provided to ATPOutputReader: {atp_result}")

        if event is None:
            raise ValueError("event object must be provided to ATPOutputReader")

        if hasattr(event, "event_1") and hasattr(event, "event_2") and event.event_1 is not None and event.event_2 is not None:
            if not hasattr(event.event_1, "event_type") or not hasattr(event.event_1, "start_time_s") or not hasattr(event.event_1, "duration_s"):
                raise ValueError(f"Event 1 in co-event missing required attributes: {event.event_1}")
            if not hasattr(event.event_2, "event_type"):
                raise ValueError(f"Event 2 in co-event missing required attributes: {event.event_2}")
            ev_type = f"{event.event_1.event_type}_{event.event_2.event_type}"
            start_s = float(event.event_1.start_time_s)
            dur_s = float(event.event_1.duration_s)
        elif hasattr(event, "event_type") and hasattr(event, "start_time_s") and hasattr(event, "duration_s"):
            ev_type = str(event.event_type)
            start_s = float(event.start_time_s)
            dur_s = float(event.duration_s)
        else:
            raise ValueError(f"Event object missing required attributes (event_type, start_time_s, duration_s): {event}")

        atp_case_path = Path(atp_result.case_path)
        freq_hz = None
        try:
            with open(atp_case_path, "r", encoding="utf-8", errors="ignore") as f:
                for line in f:
                    if "POWER FREQUENCY" in line:
                        parts = line.split("POWER FREQUENCY")
                        if len(parts) > 1:
                            val_str = parts[1].strip().rstrip(".")
                            freq_hz = float(val_str)
                        break
        except Exception as e:
            raise ValueError(f"Failed to read ATP circuit case file '{atp_case_path}': {e}") from e

        if freq_hz is None:
            raise ValueError(f"POWER FREQUENCY not found or invalid in ATP circuit case file: {atp_case_path}")

        event_metadata = {
            "event_type": ev_type,
            "start_time_s": start_s,
            "duration_s": dur_s
        }

        output_path = atp_result.case_path.with_suffix(".pl4")
        if not output_path.exists():
            raise FileNotFoundError(f"ATP .pl4 output file not found: {output_path}")

        # Check if binary PL4
        bin_path = output_path.with_suffix(".pl4.bin")
        if not bin_path.exists() and output_path.exists():
            try:
                with open(output_path, "rb") as f:
                    header = f.read(100)
                is_binary = b"PL4:" not in header and b"C  PL4" not in header
            except Exception as e:
                raise ValueError(f"Failed to read header from ATP .pl4 file '{output_path}': {e}") from e
            if is_binary:
                bin_path = output_path

        if bin_path.exists():
            read_fn = None
            try:
                import pyatp
                read_fn = getattr(pyatp, "read_pl4", None)
            except ImportError:
                try:
                    import atp_utils
                    read_fn = getattr(atp_utils, "read_pl4", None)
                except ImportError:
                    read_fn = None

            data_matrix = None
            if read_fn is not None:
                try:
                    dfHEAD, data, miscData = read_fn(str(bin_path))
                    data_matrix = data
                except Exception:
                    data_matrix = None

            if data_matrix is None:
                try:
                    data_matrix = _parse_native_binary_pl4(bin_path)
                except Exception as e:
                    raise ValueError(f"Failed to parse binary PL4 file '{bin_path}': {e}") from e

            if data_matrix is None or data_matrix.shape[0] == 0 or data_matrix.shape[1] < 7:
                raise ValueError(f"Binary PL4 file '{bin_path}' contains insufficient data columns/rows: {data_matrix.shape if data_matrix is not None else None}")

            target_len = data_matrix.shape[0]
            t = data_matrix[:target_len, 0]

            voltages = {transformer_id: data_matrix[:target_len, 1:4]}
            currents = {transformer_id: data_matrix[:target_len, 4:7]}

            return EMTWaveforms(t, voltages, currents, event_metadata, frequency_hz=freq_hz)

        # Text-based PL4 reader
        try:
            with open(output_path, "r", encoding="utf-8", errors="ignore") as f:
                lines = [line.strip() for line in f if line.strip()]
        except Exception as e:
            raise ValueError(f"Failed to read lines from text PL4 file '{output_path}': {e}") from e

        data_rows = []
        for line in lines:
            if not line.startswith("C") and not line.startswith("/") and not line.startswith("$") and not line.startswith("PL4:"):
                parts = line.split()
                try:
                    vals = [float(p) for p in parts]
                    if len(vals) >= 7:
                        data_rows.append(vals)
                except ValueError:
                    pass

        if len(data_rows) == 0:
            dbg_path = output_path.with_suffix(".dbg")
            dbg_content = ""
            if dbg_path.exists():
                try:
                    dbg_content = f"\n--- ATP DBG Log Output ---\n{dbg_path.read_text(errors='replace')[-2000:]}"
                except Exception:
                    pass
            lis_path = output_path.with_suffix(".lis")
            lis_content = ""
            if lis_path.exists():
                try:
                    lis_content = f"\n--- ATP LIS Log Output ---\n{lis_path.read_text(errors='replace')[-2000:]}"
                except Exception:
                    pass
            err_msg = f"ATP .pl4 file '{output_path}' contains no valid 7-column numeric waveform data rows.{dbg_content}{lis_content}"
            print(f"ERROR: {err_msg}")
            raise ValueError(err_msg)

        data_arr = np.array(data_rows)
        target_len = data_arr.shape[0]
        t = data_arr[:, 0]

        voltages = {transformer_id: data_arr[:, 1:4]}
        currents = {transformer_id: data_arr[:, 4:7]}

        return EMTWaveforms(t, voltages, currents, event_metadata, frequency_hz=freq_hz)
